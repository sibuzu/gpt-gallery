// Runtime design loader
// Netlify serves the image files; GitHub supplies the directory listing.
// The array above is an offline fallback and dimension cache, not a required build output.
(async () => {
  const sourceScript = new URL(document.currentScript.src);
  const snapshot = window.__GALLERY_IMAGES__;
  const repository = "sibuzu/gpt-gallery";
  const branch = "main";
  const prefix = "sites/design/images/";
  const cacheKey = `gpt-design-catalog:${repository}:${branch}`;
  const status = document.createElement("p");
  status.className = "meta";
  status.setAttribute("role", "status");
  status.textContent = "正在載入圖片清單…";
  document.querySelector("main").prepend(status);

  let cached = null;
  try {
    const saved = JSON.parse(window.localStorage.getItem(cacheKey));
    if (saved && Array.isArray(saved.images)) {
      cached = saved;
    }
  } catch (error) {
    // Storage may be unavailable in private browsing.
  }

  async function githubJSON(path) {
    const response = await fetch(`https://api.github.com/repos/${repository}/${path}`, {
      headers: { Accept: "application/vnd.github+json" },
      cache: "no-cache",
      signal: AbortSignal.timeout(15000),
    });
    if (!response.ok) throw new Error(`GitHub catalogue: HTTP ${response.status}`);
    return response.json();
  }

  async function imageDirectoryHash() {
    const parent = prefix.replace(/images\/$/, "").replace(/\/$/, "");
    const entries = await githubJSON(`contents/${parent}?ref=${encodeURIComponent(branch)}`);
    const directory = Array.isArray(entries)
      && entries.find((entry) => entry.name === "images" && entry.type === "dir");
    if (!directory || !/^[a-f0-9]{40}$/.test(directory.sha)) {
      throw new Error("GitHub did not return an images directory hash");
    }
    return directory.sha;
  }

  async function readCatalog(hash) {
    // Fetch this exact directory tree so a later push cannot mix listing versions.
    const listing = await githubJSON(`git/trees/${hash}?recursive=1`);
    if (listing.truncated || !Array.isArray(listing.tree)) {
      throw new Error("GitHub returned an incomplete directory listing");
    }

    const files = listing.tree
      .filter((entry) => entry.type === "blob" && entry.mode !== "120000")
      .map((entry) => ({ ...entry, path: prefix + entry.path }));
    const descriptions = new Set(files.map((entry) => entry.path));
    const metadata = new Map([...snapshot, ...(cached ? cached.images : [])].map((image) => [image.src, image]));
    const byPath = new Map(files.map((file) => [file.path, file]));
    const images = [];
    const compare = (left, right) => left < right ? -1 : left > right ? 1 : 0;
    const numbers = { 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10 };
    const preferred = ["現代", "雲紗", "雅裁", "線舞", "元素", "民族"];
    function categoryRank(category) {
      if (preferred.includes(category)) return preferred.indexOf(category) + 1;
      if (!category.startsWith("設計")) return 10000;
      const suffix = category.slice(2);
      if (numbers[suffix]) return numbers[suffix];
      if (/^十[一二三四五六七八九]$/.test(suffix)) return 10 + numbers[suffix[1]];
      if (/^[一二三四五六七八九]十[一二三四五六七八九]?$/.test(suffix)) {
        return numbers[suffix[0]] * 10 + (numbers[suffix[2]] || 0);
      }
      return 10000;
    }
    files.sort((left, right) => {
      const leftCategory = left.path.slice(prefix.length).split("/")[0];
      const rightCategory = right.path.slice(prefix.length).split("/")[0];
      return categoryRank(leftCategory) - categoryRank(rightCategory)
        || compare(leftCategory, rightCategory) || compare(left.path, right.path);
    });
    for (const file of files) {
      if (!file.path.startsWith(prefix)) continue;
      const parts = file.path.slice(prefix.length).split("/");
      if (parts.length !== 2) continue;
      const [category, filename] = parts;
      if (!/\.(png|jpe?g|webp|gif)$/i.test(filename)) continue;
      const src = `images/${category}/${filename}`;
      const known = metadata.get(src);
      const image = {
        category,
        src,
        title: filename.replace(/\.[^.]+$/, "").replace(/^ChatGPT Image /, "").trim(),
        hasDescription: descriptions.has(file.path.replace(/\.[^.]+$/, ".md")),
        ...(known ? { width: known.width, height: known.height } : {}),
      };
      const markdown = byPath.get(file.path.replace(/\.[^.]+$/, ".md"));
      if (markdown) {
        if (known && known.descriptionSha === markdown.sha) {
          image.descriptionSha = markdown.sha;
          if (known.description) image.description = known.description;
        } else {
          image.markdown = markdown;
        }
      }
      images.push(image);
    }

    // Only new or changed Markdown needs fetching; keep requests bounded.
    const pending = images.filter((image) => image.markdown);
    await Promise.all(Array.from({ length: Math.min(6, pending.length) }, async () => {
      while (pending.length) {
        const image = pending.shift();
        const markdown = image.markdown;
        delete image.markdown;
        try {
          const url = new URL("../", sourceScript);
          url.pathname += markdown.path.replace(/^sites\/design\//, "").split("/").map(encodeURIComponent).join("/");
          const response = await fetch(url, { cache: "no-cache", signal: AbortSignal.timeout(10000) });
          if (!response.ok) throw new Error(`Markdown: HTTP ${response.status}`);
          const description = singleLineDescription(await response.text());
          if (description) image.description = description;
          image.descriptionSha = markdown.sha;
        } catch (error) {
          console.warn("Could not refresh an image description:", error);
        }
      }
    }));
    return images;
  }

  function singleLineDescription(markdown) {
    const lines = markdown.split(/\r?\n/).map((line) => line.trim().replace(/\s+/g, " ")).filter(Boolean);
    if (lines.length && lines[0].startsWith("[") && lines[0].endsWith("]")) return lines[0];
    if (lines.length !== 1) return null;
    let text = lines[0];
    if ((text.match(/[.!?。！？]/g) || []).length > 1) return null;
    text = text.replace(/^[\uFEFF\u200B\u200C\u200D]+/, "");
    const cleaned = text.replace(/^(?:(?:she\s+)?is\s+wearing|wearing)\s+/i, "");
    if (cleaned !== text) text = cleaned.replace(/\.$/, "");
    return text && text.split(/\s+/).length <= 15 ? text : null;
  }

  try {
    if (window.location.protocol === "file:") {
      window.__GALLERY_IMAGES__ = snapshot;
      status.remove();
    } else {
      // Check on every page load; only download the listing when its hash changes.
      const hash = await imageDirectoryHash();
      window.__GALLERY_IMAGES__ = cached && cached.hash === hash ? cached.images : await readCatalog(hash);
      try {
        window.localStorage.setItem(cacheKey, JSON.stringify({ hash, images: window.__GALLERY_IMAGES__ }));
      } catch (error) {
        // A full or disabled storage must not prevent rendering.
      }
      status.remove();
    }
  } catch (error) {
    console.warn("Could not refresh the design catalogue:", error);
    window.__GALLERY_IMAGES__ = cached ? cached.images : snapshot;
    status.textContent = "目前顯示已儲存的圖片清單，稍後重新整理以取得更新。";
  }

  const designScript = document.createElement("script");
  const designURL = new URL("design.js", sourceScript);
  designURL.search = sourceScript.search;
  designScript.src = designURL.href;
  designScript.onerror = () => {
    status.textContent = "圖片庫載入失敗，請重新整理頁面。";
    document.querySelector("main").prepend(status);
  };
  document.head.append(designScript);
})();
